# Arithmetic Operators

# Used for mathematical calculations.

# +     Addition
# -     Subtraction
# *     Multiplication
# /     Division
# //    Floor Division
# %     Modulus
# **    Exponent

a = 10
b = 20

print(a + b)
print(a - b)
print(a * b)
print(a / b)
print("Floor Division",a // b)
print(a % b)
print(a ** b)