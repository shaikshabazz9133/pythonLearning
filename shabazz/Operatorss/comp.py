# Comparison Operators

# Used to compare values.

# ==    Equal
# !=    Not equal
# >     Greater than
# <     Less than
# >=    Greater than or equal
# <=    Less than or equal

age = 25

print(age == 25) #True
print(age != 25) #True
print(age > 25) #True
print(age < 25) #False
print(age >= 25) #True
print(age <= 25) #False
