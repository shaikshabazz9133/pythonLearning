# Control Statement 

# Control statements are used to control the flow of execution of a Python program.

# Normally Python executes code:

# Line 1
#   ↓
# Line 2
#   ↓
# Line 3
#   ↓
# Line 4

# Control statements allow us to change this flow.

# For example:

# if condition is true
#        ↓
# execute this block
# else
#        ↓
# execute another block

# Types of Control Statements

# Python control flow can broadly be divided into:

# Control Statements
# │
# ├── Conditional Statements
# │   ├── if
# │   ├── if-else
# │   ├── if-elif-else
# │   └── nested if
# │
# ├── Looping Statements
# │   ├── for
# │   ├── while
# │   └── nested loops
# │
# └── Jump Statements
#     ├── break
#     ├── continue
#     └── pass